# «Вторая вкладка» — то же, что «вкладка два». Порядковые формы уже
# есть в RESULT_WORDS, поэтому не дублируем их вручную.
TAB_WORDS.update({word: number for word, number in RESULT_WORDS.items() if number <= 10})


def parse_tab(raw: str) -> int | None:
    """Номер вкладки: «2», «два», «десять». Допустимый диапазон 1–10."""
    value = normalize(raw)
    if not value:
        return None
    try:
        number = int(value)
    except ValueError:
        number = TAB_WORDS.get(value)
    if number is None or not 1 <= number <= 10:
        return None
    return number


def parse_ordinal(raw: str, words_only: bool = False) -> int | None:
    """Порядковый номер результата: «2», «вторую», «третий»."""
    value = normalize(raw)
    if not value:
        return None
    if value.isdigit():
        if words_only:
            return None
        number = int(value)
    else:
        number = RESULT_WORDS.get(value)
    if number is None or not 1 <= number <= 10:
        return None
    return number
