"""Правила длительности факта: временное состояние или постоянное предпочтение.

Модель не решает, насколько устойчив факт. Это правило по словам:
здоровье, настроение и короткие периоды считаются временными, вкусы и всё
остальное — постоянными. В сомнительном случае выбирается ``permanent``:
конфликт уйдёт на проверку, а не заменит факт молча.
"""

from __future__ import annotations

TEMPORARY = "temporary"
PERMANENT = "permanent"

# Вкусы и привязанности меняются только явно: «больше не люблю», «теперь
# предпочитаю». Проверяются раньше временных маркеров: «сегодня люблю»
# остаётся предпочтением.
_PREFERENCE = (
    "люблю",
    "любит",
    "любим",
    "любят",
    "любил",
    "любила",
    "любимый",
    "любимая",
    "нравится",
    "нравятся",
    "предпочита",
    "обожа",
    "увлека",
    "мечта",
    "привык",
    "терпеть не могу",
    "не переношу",
    "фанат",
)

# Здоровье, эмоции и короткие периоды. Такие состояния естественно
# устаревают: более позднее утверждение может заменить старое.
_TEMPORARY = (
    "боле",
    "болит",
    "приболе",
    "выздоров",
    "здоров",
    "температур",
    "самочувств",
    "полегчало",
    "тошн",
    "насморк",
    "кашел",
    "таблет",
    "лекарств",
    "врач",
    "больниц",
    "устал",
    "бессонн",
    "выспал",
    "плохо",
    "хуже",
    "лучше",
    "нормально",
    "злюсь",
    "злится",
    "груст",
    "тревог",
    "стресс",
    "нерв",
    "плачу",
    "страшн",
    "одинок",
    "депресс",
    "настроени",
    "счастлив",
    "сегодня",
    "вчера",
    "сейчас",
    "временно",
    "на этой неделе",
    "в последнее время",
    "с утра",
    "весь день",
    "всю ночь",
)


def classify_durability(text: str) -> str:
    """Возвращает ``temporary`` для состояния и ``permanent`` для черты."""
    flat = " ".join((text or "").lower().replace("ё", "е").split())
    if any(marker in flat for marker in _PREFERENCE):
        return PERMANENT
    if any(marker in flat for marker in _TEMPORARY):
        return TEMPORARY
    return PERMANENT
