def classify_scope(text: str) -> str:
    """Возвращает ``trait``, ``event`` или ``state`` по словам.

    Предпочтение сильнее времени: «сегодня люблю кофе» остаётся чертой.
    Затем проверяется событие, потом состояние. Сомнительное считается
    чертой: лучше сохранить, чем молча потерять.
    """
    flat = " ".join((text or "").lower().replace("ё", "е").split())
    if any(marker in flat for marker in _PREFERENCE):
        return TRAIT
    if any(marker in flat for marker in _EVENT):
        return EVENT
    if any(marker in flat for marker in _TEMPORARY):
        return STATE
    return TRAIT
