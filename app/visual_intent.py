"""Правила для вопроса «это про экран или нет».

Модуль не ходит в сеть: здесь только промпт для decisions-модели и
дешёвый фильтр кандидатов. Сам запрос делает
``IntentClassifier.classify_visual``. Фильтр нужен, чтобы обычные фразы
не тратили вызов модели: команды, Q&A и разговор без указателей решаются
старым путём.
"""

from __future__ import annotations

import re

from .text import normalize

SCREEN = "screen"
OTHER = "other"
VISUAL_INTENTS = frozenset({SCREEN, OTHER})

# Вопрос к decisions-модели. Картинка сюда не передаётся: модель решает
# только по тексту и последнему вопросу Луны, поэтому вызов дешёвый.
VISUAL_QUESTION = {
    "type": "choice",
    "instructions": (
        "Ты решаешь, относится ли реплика пользователя к тому, что сейчас "
        "видно на его экране. Луна в режиме наблюдения уже держит свежий "
        "кадр экрана, но не описывает его без вопроса. Реплика может быть "
        "вопросом, просьбой помочь или коротким комментарием. Не считай "
        "screen общие вопросы, команды и ссылки на прошлый снимок."
    ),
    "criteria": {
        SCREEN: (
            "Спрашивает или просит помочь с тем, что видно сейчас: ошибка, "
            "окно, кнопка, текст, изображение, «что тут», «это нормально», "
            "«как это исправить», «что происходит»."
        ),
        OTHER: (
            "Общий вопрос, погода, новости, поиск, разговор о Луне, команда, "
            "воспоминание или ссылка на прошлый снимок или фото."
        ),
    },
}

# Явные указатели на текущий экран. Этого мало для ответа: модель всё
# равно решает, вопрос это о снимке или о чём-то другом.
_CANDIDATE_RE = re.compile(
    r"\b(?:это|этот|эта|эти|этого|этой|этом|этих|"
    r"тут|здесь|там|"
    r"экран\w*|окн\w*|ошибк\w*|кнопк\w*|текст\w*|надпис\w*|"
    r"написан\w*|видн\w*|видишь|виден|происходит|произошл\w*|случилось|"
    r"проблем\w*|сломал\w*|завис\w*|тормоз\w*|глючит\w*|фигн\w*|"
    r"исправ\w*|не\s+так|не\s+работает|не\s+открыва\w*|"
    r"угол|углу|угла|слева|справа|сверху|снизу)\b",
    re.UNICODE,
)


def looks_visual(text: str) -> bool:
    """Похоже ли на вопрос о том, что сейчас на экране.

    Это только фильтр кандидатов: окончательное решение принимает
    decisions-модель. Без маркеров фраза не тратит запрос.
    """
    normalized = normalize(text)
    return bool(normalized and _CANDIDATE_RE.search(normalized))


