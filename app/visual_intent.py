"""Правила для вопроса «это про экран или нет».

Модуль не ходит в сеть: здесь только промпт для decisions-модели и
дешёвый фильтр кандидатов. Сам запрос делает
``IntentClassifier.classify_visual``. Фильтр нужен, чтобы обычные фразы
не тратили вызов модели: команды, Q&A и разговор без указателей решаются
старым путём.
"""

from __future__ import annotations

import re

from .text import normalize

SCREEN = "screen"
OTHER = "other"
VISUAL_INTENTS = frozenset({SCREEN, OTHER})

# Вопрос к decisions-модели. Картинка сюда не передаётся: модель решает
# только по тексту, контексту разговора и состоянию наблюдения, поэтому
# вызов дешёвый.
VISUAL_QUESTION = {
    "type": "choice",
    "instructions": (
        "Ты решаешь, относится ли реплика пользователя к тому, что сейчас "
        "видно на его экране. В state есть последние реплики разговора "
        "(dialog_context) и состояние наблюдения (screen_state). Если "
        "наблюдение включено и кадр свежий, Луна ответит по нему. Слова "
        "«смотри», «посмотри», «глянь» сами по себе не делают вопрос "
        "экранным: «смотри, а что такое шоколад» — общий вопрос, «смотри, "
        "что у меня выделено» — про экран. Учитывай контекст разговора, "
        "но новая общая тема важнее прошлой темы экрана. Просьба посмотреть "
        "фильм, видео или музыку — это команда, а не вопрос об экране. "
        "Не считай screen команды, общие вопросы и ссылки на прошлый снимок."
    ),
    "criteria": {
        SCREEN: (
            "Просит посмотреть на экран или на то, что на нём: выделение, "
            "курсор, окно, ошибка, кнопка, текст, изображение. Спрашивает, "
            "что видно, что происходит, что я делаю, чем я занят, как это "
            "исправить."
        ),
        OTHER: (
            "Общий вопрос или факт, даже если начинается со «смотри/посмотри»: "
            "погода, новости, поиск, разговор о Луне; команда, в том числе "
            "включить или посмотреть фильм, видео, музыку; воспоминание или "
            "ссылка на прошлый снимок или фото."
        ),
    },
}

# Явные указатели на текущий экран и просьбы посмотреть. Этого мало для
# ответа: модель всё равно решает, вопрос это о снимке или о чём-то другом.
# «Смотри, а что такое шоколад» проходит фильтр, но модель относит фразу
# к other по смыслу и контексту. Вопросы о текущем занятии («что я сейчас
# делаю») тоже кандидаты: при активном наблюдении ответ по кадру уместнее,
# чем «я не вижу твой экран».
_CANDIDATE_RE = re.compile(
    r"\b(?:это|этот|эта|эти|этого|этой|этом|этих|"
    r"тут|здесь|там|"
    r"посмотри|посмотрите|смотри|смотрите|глянь|гляньте|взгляни|взгляните|"
    r"экран\w*|окн\w*|ошибк\w*|кнопк\w*|текст\w*|надпис\w*|"
    r"выделен\w*|выделил\w*|выделя\w*|курсор\w*|скриншот\w*|"
    r"написан\w*|видн\w*|видишь|виден|происходит|произошл\w*|случилось|"
    r"проблем\w*|сломал\w*|завис\w*|тормоз\w*|глючит\w*|фигн\w*|"
    r"исправ\w*|не\s+так|не\s+работает|не\s+открыва\w*|"
    r"что\s+(?:я\s+)?(?:сейчас\s+|тут\s+|здесь\s+)?"
    r"(?:делаю|делал[аи]?|буду\s+делать)|"
    r"чем\s+(?:я\s+)?(?:сейчас\s+)?(?:занят\w*|занима\w*)|"
    r"что\s+у\s+меня\s+(?:сейчас\s+)?происходит|"
    r"угол|углу|угла|слева|справа|сверху|снизу)\b",
    re.UNICODE,
)

# Прямая просьба посмотреть: «смотри/посмотри + вопрос или деталь экрана».
# Нужна, чтобы спросить модель даже без активного наблюдения. Это не
# команда снимка: окончательное решение всё равно за моделью, поэтому
# «смотри, а что такое шоколад» останется обычным разговором.
_LOOK_START_RE = re.compile(
    r"^(?:(?:а|ну|и|так|давай)\s+)*"
    r"(?:посмотри|посмотрите|смотри|смотрите|глянь|гляньте|взгляни|взгляните)\b",
    re.UNICODE,
)
_LOOK_TOPIC_RE = re.compile(
    r"\b(?:что|где|какой|какая|какое|какие|чего|чем|сколько|кто|почему|зачем|"
    r"экран\w*|выделен\w*|выделил\w*|выделя\w*|курсор\w*|"
    r"скриншот\w*|снимок|снимке|фото)\b",
    re.UNICODE,
)


def looks_visual(text: str) -> bool:
    """Похоже ли на вопрос о том, что сейчас на экране.

    Это только фильтр кандидатов: окончательное решение принимает
    decisions-модель. Без маркеров фраза не тратит запрос.
    """
    normalized = normalize(text)
    return bool(normalized and _CANDIDATE_RE.search(normalized))


def looks_like_look_request(text: str) -> bool:
    """Прямая просьба посмотреть, даже если кадра ещё нет.

    Позволяет спросить decisions-модель без активного наблюдения. Модель
    решает по контексту: «смотри, что выделено» — про экран, «смотри, а
    что такое шоколад» — обычный вопрос.
    """
    normalized = normalize(text)
    return bool(
        normalized and _LOOK_START_RE.match(normalized) and _LOOK_TOPIC_RE.search(normalized)
    )


